"""TEST-ONLY deterministic executor.

Runs test-authored / scripted-mock commands on the host for offline e2e tests.
This is NOT a production backend: real-mode untrusted execution must go through
the Docker sandbox (safefix.runtime.docker_executor). Commands here are trusted
because they are written by the test suite, not generated by a live model.
"""

from __future__ import annotations

import asyncio
import time
from pathlib import Path

from safefix.runtime.executor import ExecResult


class TrustedLocalExecutor:
    def __init__(self):
        self.commands: list[str] = []

    async def run(self, command: str, *, cwd: Path, timeout: float) -> ExecResult:
        self.commands.append(command)
        start = time.monotonic()
        proc = await asyncio.create_subprocess_shell(
            command,
            cwd=cwd,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        try:
            out, err = await asyncio.wait_for(proc.communicate(), timeout=timeout)
            return ExecResult(
                stdout=out.decode("utf-8", "replace"),
                stderr=err.decode("utf-8", "replace"),
                exit_code=proc.returncode or 0,
                duration_s=time.monotonic() - start,
            )
        except TimeoutError:
            proc.kill()
            await proc.wait()
            return ExecResult(exit_code=-1, timed_out=True)
